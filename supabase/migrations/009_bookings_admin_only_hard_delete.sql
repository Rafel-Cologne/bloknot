-- Раньше владелец мог физически (жёстко) удалить бронь через RLS-политику
-- "bookings: owner delete" — из-за этого удалённые брони пропадали из БД навсегда
-- и не попадали в админскую вкладку "Восстановление" (которая рассчитана на soft-delete
-- через deleted_at). Теперь окончательное удаление доступно только администратору
-- (политика "bookings: admin full" уже даёт админу ALL, включая DELETE) — обычный
-- владелец может только "заархивировать" бронь (проставить deleted_at через UPDATE,
-- на что у него уже есть право по политике "bookings: owner update").
drop policy if exists "bookings: owner delete" on public.bookings;
